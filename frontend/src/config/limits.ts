/**
 * Потолки списков на дашборде (в строках).
 *
 * Здесь, а не по месту: число читается в двух местах — боевой запрос боковой
 * очереди и прогон витрины, — и разъехаться им нельзя, иначе оператор увидит
 * разные длины одного и того же списка.
 */

/**
 * Сколько строк тянет боковая очередь загрузки.
 *
 * Ровно столько, сколько влезает в карточку боковой очереди без прокрутки:
 * лишнее — это строки, которые видны только после скролла, а оператор до
 * них не дотянется без мыши.
 */
export const SIDEBAR_ROW_LIMIT = 20;

/**
 * Сколько строк просим у API для боковой очереди.
 *
 * С запасом: часть строк книги приходит без времени (очередь загрузки), и в
 * карточку идут только шесть ближайших к выгрузке. Если просить ровно потолок
 * карточки, этот фильтр съедает место и внизу остаётся просвет вместо строк.
 */
export const SIDEBAR_FETCH_LIMIT = SIDEBAR_ROW_LIMIT + 20;
